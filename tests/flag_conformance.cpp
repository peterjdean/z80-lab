#include "cpu.hpp"
#include <cstdint>
#include <iostream>
#include <cstdlib>
using namespace z80emu;

[[noreturn]] static void fail(const char* label, int a, int f, int op, int expected, int actual) {
    std::cerr << "FAIL " << label << " A/byte=" << hex8(a)
              << " initial F/addr-high=" << hex8(f) << " opcode/bit=" << hex8(op)
              << " expected F=" << hex8(expected) << " actual F=" << hex8(actual) << '\n';
    std::exit(1);
}
static bool parity(uint8_t v) {
    int bits=0;
    for(int i=0;i<8;++i) bits += (v>>i)&1;
    return !(bits&1);
}

// Independent reference based on Z80 decimal-adjust correction and post-DAA flags.
// Inputs include every A value and each possible prior (N,H,C) state, including
// states not typically generated by a preceding valid BCD arithmetic operation.
static uint16_t daaReference(uint8_t a, uint8_t flags) {
    bool n=flags&FN, h=flags&FH, c=flags&FC;
    int correction=0;
    if(h || (a&15)>9) correction += 6;
    if(c || a>0x99) { correction += 0x60; c=true; }
    bool newHalf = n ? (h && (a&15)<6) : ((a&15)>=10);
    uint8_t result = n ? uint8_t(a-correction) : uint8_t(a+correction);
    uint8_t f = (result&(FS|FY|FX)) | (result==0?FZ:0) |
                (parity(result)?FP:0) | (n?FN:0) | (newHalf?FH:0) | (c?FC:0);
    return uint16_t(result<<8 | f);
}

int main() {
    Cpu cpu;
    // DAA: 256 accumulator inputs x 8 combinations of N,H,C.
    for(int a=0;a<256;++a) for(int flags=0;flags<8;++flags) {
        uint8_t f = (flags&1?FC:0)|(flags&2?FN:0)|(flags&4?FH:0);
        cpu.reg.a=uint8_t(a);cpu.reg.f=f;
        cpu.reg.pc=0x100;cpu.reg.halted=false;cpu.mem[0x100]=0x27;
        cpu.step();
        uint16_t expected=daaReference(uint8_t(a),f);
        if(cpu.af()!=expected)
            fail("DAA",a,f,0x27,expected,cpu.af());
    }
    // Test BIT b,r for all 256 operands, each bit and both C flag settings.
    for(int value=0;value<256;++value) for(int bit=0;bit<8;++bit)
      for(int carry=0;carry<=1;++carry) {
        cpu.reg.b=uint8_t(value); cpu.reg.f=carry?FC:0;
        cpu.reg.pc=0x100;cpu.reg.halted=false;
        cpu.mem[0x100]=0xcb;cpu.mem[0x101]=uint8_t(0x40 + 8*bit); // BIT bit,B
        cpu.step();
        bool zero=!(value & (1<<bit));
        uint8_t expected = (value&(FX|FY)) | FH | (zero?(FZ|FP):0) |
                           ((bit==7&&!zero)?FS:0) | (carry?FC:0);
        if(cpu.reg.f!=expected) fail("BIT b,B",value,carry,bit,expected,cpu.reg.f);
    }
    // Test BIT b,(HL): undocumented bits come from H (MEMPTR high), not operand.
    for(int value=0;value<256;++value) for(int bit=0;bit<8;++bit)
      for(int high : {0x00, 0x08, 0x20, 0x28, 0xff}) {
        uint16_t addr=uint16_t((high<<8)|0x55);
        cpu.setHL(addr); cpu.mem[addr]=uint8_t(value); cpu.reg.f=FC;
        cpu.reg.pc=0x100;cpu.reg.halted=false;
        cpu.mem[0x100]=0xcb;cpu.mem[0x101]=uint8_t(0x46 + 8*bit); // BIT bit,(HL)
        cpu.step();
        bool zero=!(value & (1<<bit));
        uint8_t expected = (high&(FX|FY)) | FH | (zero?(FZ|FP):0) |
                           ((bit==7&&!zero)?FS:0) | FC;
        if(cpu.reg.f!=expected) fail("BIT b,(HL)",value,high,bit,expected,cpu.reg.f);
    }
    // Indexed BIT: MEMPTR is effective IX+d; check a displacement carrying over page.
    for(int value=0;value<256;++value) for(int bit=0;bit<8;++bit) {
        cpu.reg.ix=0x20ff;cpu.mem[0x2101]=uint8_t(value);cpu.reg.f=FC;
        cpu.reg.pc=0x100;cpu.reg.halted=false;
        cpu.mem[0x100]=0xdd;cpu.mem[0x101]=0xcb;cpu.mem[0x102]=2;
        cpu.mem[0x103]=uint8_t(0x46 + 8*bit); // BIT bit,(IX+2)
        cpu.step();
        bool zero=!(value & (1<<bit));
        uint8_t expected = (0x21&(FX|FY)) | FH | (zero?(FZ|FP):0) |
                           ((bit==7&&!zero)?FS:0) | FC;
        if(cpu.reg.f!=expected) fail("BIT b,(IX+d)",value,0x21,bit,expected,cpu.reg.f);
    }
    std::cout << "PASS: DAA 2,048 states; BIT reg 4,096 cases; BIT (HL) 10,240 cases; "
              << "BIT (IX+d) 2,048 cases\n";
}
